const assert=require('node:assert/strict');
const fs=require('node:fs');
const {encounterSources,knownStands,sessionStands,evidenceExcerpt}=require('../docs/assets/stand-visibility.js');
const edition=JSON.parse(fs.readFileSync('docs/data/editorial-public-v1.json','utf8'));
const recaps=JSON.parse(fs.readFileSync('docs/data/session-formats.json','utf8'));
const published=recaps.sessions['sessione-fiume-01'];
assert(published && published.standard.includes('POOR SOULS'),"The published river recap names POOR SOULS");
assert(edition.profiles['stand-poor-souls']?.summary.includes('POOR SOULS'));
const poor={id:'stand-poor-souls',kind:'stand',title:'POOR SOULS',summary:edition.profiles['stand-poor-souls'].summary,public:true};
const variants=[published.standard,published.concise,published.combat,...published.outline.flatMap(group=>group.events||[])];
const first={id:'sessione-fiume-01',title:'La prova del fiume',number:1,public:true,summary:'Il gruppo supera il fiume.',events:[],recapVariants:variants};
const second={id:'sessione-2',number:2,public:true,summary:'Gli Stand non vengono nominati.',events:[]};
assert.deepEqual(knownStands([poor],[first,second]).map(e=>e.title),['POOR SOULS']);
assert.deepEqual(sessionStands([poor],[first,second],first).map(e=>e.id),['stand-poor-souls']);
assert.deepEqual(sessionStands([poor],[first,second],second),[]);
assert.deepEqual(sessionStands([poor],[{...first,public:false}],{...first,public:false}),[]);
assert(evidenceExcerpt(first,'POOR SOULS').includes('POOR SOULS'));
const client=fs.readFileSync('docs/assets/app-v2.js','utf8');
assert(client.includes("edition.profiles?.['stand-poor-souls']"),"Editorial dossier integrated");
assert(client.includes('s.recapVariants=[f.standard,f.concise,f.combat'),"Recap variants integrated");
const masterJs=fs.readFileSync('docs/assets/master-v2.js','utf8');
const masterHtml=fs.readFileSync('docs/master.html','utf8');
assert(!masterJs.includes('/auth/v1/signup'),"No client signup request");
assert(!masterHtml.includes('id="signup"'),"No public signup button");
assert(masterJs.includes("/rest/v1/rpc/is_admin"),"Admin role checked");
console.log('PASS: POOR SOULS public encounter, per-session membership and restricted signup UI');
